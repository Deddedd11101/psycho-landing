/**
 * Простой типограф: убирает висячие предлоги и разрывы, которые цепляют глаз.
 *
 * Что делает:
 *  - короткие слова (предлоги, союзы, частицы) приклеиваются к следующему слову;
 *  - число не отрывается от «₽», «мин», «ч.», «%», «лет» и т.п.;
 *  - разряды в числах («1 500») не разрываются;
 *  - тире не уезжает на новую строку одно — пробел перед ним неразрывный.
 *
 * Применяется к текстам контента при рендере (см. компоненты лендинга).
 */

const NBSP = ' ';

/** Слова, после которых перенос строки выглядит плохо. */
const SHORT_WORDS = [
  'в', 'во', 'на', 'с', 'со', 'к', 'ко', 'о', 'об', 'от', 'до', 'по', 'за', 'из', 'у', 'не', 'ни', 'и', 'а', 'но',
  'да', 'что', 'как', 'же', 'ли', 'бы', 'для', 'при', 'под', 'над', 'без', 'про', 'то', 'все', 'всё', 'это',
];

const SHORT_WORDS_PATTERN = new RegExp(`(^|[\\s(«"])(${SHORT_WORDS.join('|')}) `, 'gi');

/** Единицы, которые не должны отрываться от числа. */
const UNITS_PATTERN = /(\d) (₽|мин|ч\.|лет|год|года|%|дней|день|дня)/g;

/** Разряды: «1 500» → «1 500» с неразрывным пробелом. */
const THOUSANDS_PATTERN = /(\d) (\d{3})(?!\d)/g;

/** Пробел перед тире — неразрывный, чтобы тире не начинало строку. */
const DASH_PATTERN = / — /g;

export function typo(text: string): string {
  return text
    .replace(THOUSANDS_PATTERN, `$1${NBSP}$2`)
    .replace(UNITS_PATTERN, `$1${NBSP}$2`)
    .replace(DASH_PATTERN, `${NBSP}— `)
    // Два прохода: после склейки «в доме» следующее короткое слово могло остаться с обычным пробелом.
    .replace(SHORT_WORDS_PATTERN, `$1$2${NBSP}`)
    .replace(SHORT_WORDS_PATTERN, `$1$2${NBSP}`);
}
